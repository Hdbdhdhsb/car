/* NaN->0、Inf/越界->夹边界，防止脏浮点进入发送帧 */
static float sanitize_float(float v, float lo, float hi) {
    if (v != v)  return 0.0f;    /* NaN */
    if (v < lo)  return lo;
    if (v > hi)  return hi;      /* 同时覆盖 ±Inf */
    return v;
}
